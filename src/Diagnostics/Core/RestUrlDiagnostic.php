declare(strict_types=1);

namespace WPCalibrate\RESTHealthRepair\Diagnostics\Core;

use WPCalibrate\RESTHealthRepair\Diagnostics\DiagnosticInterface;
use WPCalibrate\RESTHealthRepair\Diagnostics\DiagnosticResult;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * RestUrlDiagnostic class.
 */
final class RestUrlDiagnostic implements DiagnosticInterface {

	public function get_id(): string {
		return 'wp_rest_url';
	}

	public function get_group(): string {
		return 'core';
	}

	public function get_title(): string {
		return __( 'REST Root URL Generation', 'wpcalibrate-rest-health-repair' );
	}

	public function get_description(): string {
		return __( 'Validates that rest_url() produces a syntactically valid URL consistent with site scheme and host.', 'wpcalibrate-rest-health-repair' );
	}

	public function is_applicable(): bool {
		return true;
	}

	public function get_repair_id(): ?string {
		return null;
	}

	public function get_severity(): string {
		return DiagnosticResult::SEVERITY_WARNING;
	}

	public function run(): DiagnosticResult {
		$start_time = microtime( true );

		$rest_url = function_exists( 'rest_url' ) ? rest_url() : '';
		$home_url = home_url();

		$rest_parsed = wp_parse_url( $rest_url );
		$home_parsed = wp_parse_url( $home_url );

		$evidence = array(
			'rest_url'     => $rest_url,
			'home_url'     => $home_url,
			'rest_scheme'  => $rest_parsed['scheme'] ?? 'missing',
			'home_scheme'  => $home_parsed['scheme'] ?? 'missing',
			'rest_host'    => $rest_parsed['host'] ?? 'missing',
			'home_host'    => $home_parsed['host'] ?? 'missing',
		);

		if ( empty( $rest_url ) || false === filter_var( $rest_url, FILTER_VALIDATE_URL ) ) {
			return new DiagnosticResult(
				$this->get_id(),
				DiagnosticResult::STATUS_FAILED,
				__( 'The REST root URL generated by rest_url() is empty or invalid.', 'wpcalibrate-rest-health-repair' ),
				$evidence,
				array(
					__( 'Corrupted site_url() or home_url() configuration in wp-config.php or wp_options.', 'wpcalibrate-rest-health-repair' ),
					__( 'A custom filter hooked to rest_url returning an invalid value.', 'wpcalibrate-rest-health-repair' ),
				),
				__( 'All client-side applications, blocks, and REST consumers fail to locate endpoints.', 'wpcalibrate-rest-health-repair' ),
				__( 'Check Settings > General for Site Address (URL) and WordPress Address (URL) validity.', 'wpcalibrate-rest-health-repair' ),
				null,
				__( '1. Check wp-config.php for WP_HOME and WP_SITEURL constants. 2. Ensure both have valid http:// or https:// schemas.', 'wpcalibrate-rest-health-repair' ),
				DiagnosticResult::SEVERITY_CRITICAL,
				time(),
				( microtime( true ) - $start_time ) * 1000
			);
		}

		if ( ( $rest_parsed['scheme'] ?? '' ) !== ( $home_parsed['scheme'] ?? '' ) ) {
			return new DiagnosticResult(
				$this->get_id(),
				DiagnosticResult::STATUS_WARNING,
				__( 'Scheme mismatch detected between REST URL and Home URL.', 'wpcalibrate-rest-health-repair' ),
				$evidence,
				array(
					__( 'Mixed content setup where Home URL is HTTPS but REST URL is HTTP (or vice versa).', 'wpcalibrate-rest-health-repair' ),
					__( 'Reverse proxy or SSL termination without HTTP_X_FORWARDED_PROTO configuration.', 'wpcalibrate-rest-health-repair' ),
				),
				__( 'Browsers may block REST requests due to mixed-content security policies.', 'wpcalibrate-rest-health-repair' ),
				__( 'Align Home URL and Site URL schemes in Settings > General or configure SSL headers in wp-config.php.', 'wpcalibrate-rest-health-repair' ),
				null,
				__( 'In wp-config.php before wp-settings.php, add proxy header detection if behind Cloudflare or a load balancer.', 'wpcalibrate-rest-health-repair' ),
				DiagnosticResult::SEVERITY_WARNING,
				time(),
				( microtime( true ) - $start_time ) * 1000
			);
		}

		return new DiagnosticResult(
			$this->get_id(),
			DiagnosticResult::STATUS_HEALTHY,
			__( 'REST root URL is valid and consistently configured with the site URL structure.', 'wpcalibrate-rest-health-repair' ),
			$evidence,
			array(),
			__( 'URL generation operates normally.', 'wpcalibrate-rest-health-repair' ),
			__( 'No action required.', 'wpcalibrate-rest-health-repair' ),
			null,
			null,
			DiagnosticResult::SEVERITY_INFO,
			time(),
			( microtime( true ) - $start_time ) * 1000
		);
	}
}
