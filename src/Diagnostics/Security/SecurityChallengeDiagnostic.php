declare(strict_types=1);

namespace WPCalibrate\RESTHealthRepair\Diagnostics\Security;

use WPCalibrate\RESTHealthRepair\Diagnostics\DiagnosticInterface;
use WPCalibrate\RESTHealthRepair\Diagnostics\DiagnosticResult;
use WPCalibrate\RESTHealthRepair\Support\Sanitizer;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * SecurityChallengeDiagnostic class.
 */
final class SecurityChallengeDiagnostic implements DiagnosticInterface {

	public function get_id(): string {
		return 'security_challenge';
	}

	public function get_group(): string {
		return 'security';
	}

	public function get_title(): string {
		return __( 'WAF, CDN & Security Challenge Detection', 'wpcalibrate-rest-health-repair' );
	}

	public function get_description(): string {
		return __( 'Detects whether Cloudflare, ModSecurity, AWS WAF, or server firewalls intercept REST API calls with HTML challenge/block pages.', 'wpcalibrate-rest-health-repair' );
	}

	public function is_applicable(): bool {
		return true;
	}

	public function get_repair_id(): ?string {
		return null; // Safety rule: Never offer one-click "disable firewall" feature.
	}

	public function get_severity(): string {
		return DiagnosticResult::SEVERITY_WARNING;
	}

	public function run(): DiagnosticResult {
		$start_time = microtime( true );
		$target_url = function_exists( 'rest_url' ) ? rest_url() : home_url( '/wp-json/' );

		$settings = (array) get_option( 'wpcalibrate_rhr_settings', array() );
		$timeout  = max( 3, min( 30, (int) ( $settings['http_timeout'] ?? 10 ) ) );

		$response = wp_remote_get(
			$target_url,
			array(
				'timeout'    => $timeout,
				'user-agent' => 'WPCalibrate-WAF-Diagnostic/1.0',
				'headers'    => array( 'Accept' => 'application/json' ),
			)
		);
		$duration = ( microtime( true ) - $start_time ) * 1000;

		if ( is_wp_error( $response ) ) {
			return new DiagnosticResult(
				$this->get_id(),
				DiagnosticResult::STATUS_UNABLE_TO_TEST,
				__( 'Could not evaluate firewall challenge due to connection failure.', 'wpcalibrate-rest-health-repair' ),
				array( 'error' => $response->get_error_message() ),
				array(),
				'',
				'',
				null,
				null,
				DiagnosticResult::SEVERITY_INFO,
				time(),
				$duration
			);
		}

		$status_code = wp_remote_retrieve_response_code( $response );
		$headers     = wp_remote_retrieve_headers( $response );
		$body        = (string) wp_remote_retrieve_body( $response );
		$body_lower  = strtolower( $body );

		$server_header = (string) wp_remote_retrieve_header( $response, 'server' );
		$is_cf_server  = str_contains( strtolower( $server_header ), 'cloudflare' );
		$has_cf_ray    = ! empty( wp_remote_retrieve_header( $response, 'cf-ray' ) );

		// Signatures of known challenge / WAF pages.
		$is_cf_challenge = ( str_contains( $body_lower, 'just a moment...' ) || str_contains( $body_lower, 'cf-turnstile' ) || str_contains( $body_lower, 'ray id:' ) ) && $is_cf_server;
		$is_wordfence    = str_contains( $body_lower, 'your access to this site has been limited' ) || str_contains( $body_lower, 'generated by wordfence' );
		$is_modsec       = 403 === $status_code && ( str_contains( $body_lower, 'mod_security' ) || str_contains( $body_lower, 'not acceptable' ) );
		$is_sucuri       = str_contains( $body_lower, 'access denied - sucuri website firewall' );

		$evidence = array(
			'status_code'     => $status_code,
			'server_header'   => Sanitizer::redact_secrets( $server_header ),
			'is_cloudflare'   => $is_cf_server,
			'has_cf_ray'      => $has_cf_ray,
			'is_cf_challenge' => $is_cf_challenge,
			'is_wordfence'    => $is_wordfence,
			'is_modsec'       => $is_modsec,
			'is_sucuri'       => $is_sucuri,
			'body_snippet'    => Sanitizer::sanitize_response_body_snippet( $body, 200 ),
			'duration_ms'     => round( $duration, 2 ),
		);

		if ( $is_cf_challenge ) {
			return new DiagnosticResult(
				$this->get_id(),
				DiagnosticResult::STATUS_FAILED,
				__( 'Cloudflare is intercepting REST requests with an interactive security challenge (CAPTCHA / Turnstile).', 'wpcalibrate-rest-health-repair' ),
				$evidence,
				array(
					__( 'Cloudflare "Bot Fight Mode" or "Super Bot Fight Mode" challenging automated requests.', 'wpcalibrate-rest-health-repair' ),
					__( 'Cloudflare WAF Custom Rule or Security Level set to "Under Attack" / "High".', 'wpcalibrate-rest-health-repair' ),
				),
				__( 'External REST clients, background sync, webhooks, and mobile apps cannot complete CAPTCHA challenges.', 'wpcalibrate-rest-health-repair' ),
				__( 'Create a Cloudflare WAF Skip rule for /wp-json/* endpoints.', 'wpcalibrate-rest-health-repair' ),
				null,
				__( "In Cloudflare Dashboard:\n1. Go to Security > WAF > Custom Rules > Create rule.\n2. Field: URI Path, Operator: starts with, Value: /wp-json/\n3. Action: Skip > WAF components (Managed Rules, Rate Limiting, Bot Fight Mode).\n4. Save and Deploy.", 'wpcalibrate-rest-health-repair' ),
				DiagnosticResult::SEVERITY_CRITICAL,
				time(),
				$duration
			);
		}

		if ( $is_wordfence ) {
			return new DiagnosticResult(
				$this->get_id(),
				DiagnosticResult::STATUS_WARNING,
				__( 'Wordfence firewall appears to be blocking or rate-limiting requests to the REST endpoint.', 'wpcalibrate-rest-health-repair' ),
				$evidence,
				array(
					__( 'Wordfence Rate Limiting rule triggered by loopback requests.', 'wpcalibrate-rest-health-repair' ),
					__( 'Wordfence Web Application Firewall blocking specific user agents or POST requests.', 'wpcalibrate-rest-health-repair' ),
				),
				__( 'Automated API requests receive Wordfence 503 block pages.', 'wpcalibrate-rest-health-repair' ),
				__( 'Check Wordfence > Tools > Live Traffic to identify why the request was blocked.', 'wpcalibrate-rest-health-repair' ),
				null,
				__( 'In Wordfence > All Options > Whitelisted Services and Rate Limiting, ensure server IP is whitelisted.', 'wpcalibrate-rest-health-repair' ),
				DiagnosticResult::SEVERITY_WARNING,
				time(),
				$duration
			);
		}

		if ( $is_modsec || $is_sucuri ) {
			return new DiagnosticResult(
				$this->get_id(),
				DiagnosticResult::STATUS_WARNING,
				__( 'Web server firewall (ModSecurity or Sucuri) returned an Access Denied / 403 block page.', 'wpcalibrate-rest-health-repair' ),
				$evidence,
				array(
					__( 'Hosting server firewall rule triggered by REST request parameters or headers.', 'wpcalibrate-rest-health-repair' ),
				),
				__( 'Specific REST calls (e.g. updating options or saving blocks) may be blocked.', 'wpcalibrate-rest-health-repair' ),
				__( 'Contact hosting support with timestamp and IP from technical evidence to whitelist rule.', 'wpcalibrate-rest-health-repair' ),
				null,
				null,
				DiagnosticResult::SEVERITY_WARNING,
				time(),
				$duration
			);
		}

		return new DiagnosticResult(
			$this->get_id(),
			DiagnosticResult::STATUS_HEALTHY,
			__( 'No active WAF or CDN challenge pages detected on the REST root endpoint.', 'wpcalibrate-rest-health-repair' ),
			$evidence,
			array(),
			__( 'Firewall allows automated REST traffic.', 'wpcalibrate-rest-health-repair' ),
			__( 'No action required.', 'wpcalibrate-rest-health-repair' ),
			null,
			null,
			DiagnosticResult::SEVERITY_INFO,
			time(),
			$duration
		);
	}
}
